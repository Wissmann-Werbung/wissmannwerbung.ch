function getPreferredLanguage() {
  const saved = localStorage.getItem('site_lang');
  if (saved && (saved === 'de' || saved === 'en')) {
    return saved;
  }
  const browserLang = (navigator.language || navigator.userLanguage || '').toLowerCase();
  if (browserLang.startsWith('en')) {
    return 'en';
  }
  return 'de';
}

